// `ts-projects completion {bash,zsh,fish}` shell completion generator.
// Identifiers derive dynamically from TOOL_DIR_NAME so template-press rebranding
// produces zero leaked tokens.
// cspell:ignore cword CWORD COMPREPLY compgen nosort compdef funcstack typeset subcommand cmds descr
import { writeFileSync } from 'node:fs';

import { Argument, type Command } from 'commander';

import type { CliContext, CliDeps } from '../deps.js';
import { TOOL_DIR_NAME } from '../xdg-paths.js';

/** Supported shell targets for `completion <shell>`. */
export const COMPLETION_SHELLS: readonly ['bash', 'zsh', 'fish'] = ['bash', 'zsh', 'fish'] as const;

/** Union of supported completion shells. */
export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

/** Build a shell completion script for the given shell target. */
export function renderCompletionScript(shell: CompletionShell): string {
  const bin = TOOL_DIR_NAME;
  const fnName = `_${bin.replaceAll('-', '_')}_completion`;
  const envPrefix = bin.toUpperCase().replaceAll('-', '_');
  const setupFn = `${fnName}_setup`;
  const completeEnv = `_${envPrefix}_COMPLETE`;

  if (shell === 'bash') {
    return [
      `# bash completion for ${bin}`,
      `${fnName}() {`,
      '    local cur prev',
      '    cur="${COMP_WORDS[COMP_CWORD]}"',
      '    prev=""',
      '    if [[ ${COMP_CWORD} -gt 0 ]]; then',
      '        prev="${COMP_WORDS[COMP_CWORD-1]}"',
      '    fi',
      '    local top_cmds="projects config doctor completion"',
      '    local projects_cmds="list get"',
      '    local config_cmds="init path get set"',
      '    local gettable_keys="logging.file logging.file_level logging.format logging.level output.color output.format token"',
      '    local settable_keys="logging.file logging.file_level logging.format logging.level output.color output.format"',
      '    local shells="bash zsh fish"',
      '    local global_opts="-o --output --json --output-file --log-level --log-file -v --verbose -q --quiet --debug --no-color --no-input --config --token -V --version -h --help"',
      '',
      '    case "${prev}" in',
      '        -o|--output)',
      '            COMPREPLY=( $(compgen -W "text json csv markdown" -- "${cur}") )',
      '            return 0',
      '            ;;',
      '        --log-level)',
      '            COMPREPLY=( $(compgen -W "debug info warning error critical" -- "${cur}") )',
      '            return 0',
      '            ;;',
      '        --source)',
      '            COMPREPLY=( $(compgen -W "http memory" -- "${cur}") )',
      '            return 0',
      '            ;;',
      '        --output-file|--config|--log-file)',
      '            COMPREPLY=( $(compgen -f -- "${cur}") )',
      '            return 0',
      '            ;;',
      '        --token)',
      '            COMPREPLY=()',
      '            return 0',
      '            ;;',
      '    esac',
      '',
      '    local -a pos=()',
      '    local i=1',
      '    while [[ ${i} -lt ${COMP_CWORD} ]]; do',
      '        local w="${COMP_WORDS[i]}"',
      '        case "${w}" in',
      '            -o|--output|--output-file|--log-level|--config|--token|--workspace|--limit|--source)',
      '                ((i += 2))',
      '                continue',
      '                ;;',
      '            --log-file)',
      '                if [[ $((i + 1)) -lt ${COMP_CWORD} ]]; then',
      '                    local nxt="${COMP_WORDS[i+1]}"',
      '                    if [[ "${nxt}" != -* && "${nxt}" != "projects" && "${nxt}" != "config" && "${nxt}" != "doctor" && "${nxt}" != "completion" ]]; then',
      '                        ((i += 2))',
      '                        continue',
      '                    fi',
      '                fi',
      '                ((i += 1))',
      '                continue',
      '                ;;',
      '            -*)',
      '                ((i += 1))',
      '                continue',
      '                ;;',
      '            *)',
      '                pos+=("${w}")',
      '                ((i += 1))',
      '                ;;',
      '        esac',
      '    done',
      '',
      '    if [[ ${#pos[@]} -eq 0 ]]; then',
      '        COMPREPLY=( $(compgen -W "${top_cmds} ${global_opts}" -- "${cur}") )',
      '        return 0',
      '    fi',
      '',
      '    case "${pos[0]}" in',
      '        projects)',
      '            if [[ ${#pos[@]} -eq 1 ]]; then',
      '                COMPREPLY=( $(compgen -W "${projects_cmds} ${global_opts}" -- "${cur}") )',
      '            else',
      '                COMPREPLY=( $(compgen -W "--workspace --limit --source --copy ${global_opts}" -- "${cur}") )',
      '            fi',
      '            ;;',
      '        config)',
      '            if [[ ${#pos[@]} -eq 1 ]]; then',
      '                COMPREPLY=( $(compgen -W "${config_cmds} ${global_opts}" -- "${cur}") )',
      '            elif [[ "${pos[1]}" == "get" && ${#pos[@]} -eq 2 ]]; then',
      '                COMPREPLY=( $(compgen -W "${gettable_keys} ${global_opts}" -- "${cur}") )',
      '            elif [[ "${pos[1]}" == "set" && ${#pos[@]} -eq 2 ]]; then',
      '                COMPREPLY=( $(compgen -W "${settable_keys} ${global_opts}" -- "${cur}") )',
      '            elif [[ "${pos[1]}" == "init" || "${pos[1]}" == "set" ]]; then',
      '                COMPREPLY=( $(compgen -W "--dry-run -y --yes ${global_opts}" -- "${cur}") )',
      '            else',
      '                COMPREPLY=( $(compgen -W "${global_opts}" -- "${cur}") )',
      '            fi',
      '            ;;',
      '        doctor)',
      '            COMPREPLY=( $(compgen -W "--bundle ${global_opts}" -- "${cur}") )',
      '            ;;',
      '        completion)',
      '            if [[ ${#pos[@]} -eq 1 ]]; then',
      '                COMPREPLY=( $(compgen -W "${shells} ${global_opts}" -- "${cur}") )',
      '            else',
      '                COMPREPLY=( $(compgen -W "${global_opts}" -- "${cur}") )',
      '            fi',
      '            ;;',
      '    esac',
      '    return 0',
      '}',
      '',
      `${setupFn}() {`,
      `    complete -o nosort -F ${fnName} ${bin}`,
      '}',
      '',
      `# ${completeEnv}`,
      `${setupFn}`,
      '',
    ].join('\n');
  }

  if (shell === 'zsh') {
    return [
      `#compdef ${bin}`,
      '',
      `${fnName}() {`,
      '    local context state state_descr line',
      '    typeset -A opt_args',
      '    local -a commands',
      '    commands=(',
      "        'projects:list and inspect projects'",
      "        'config:inspect and edit CLI configuration'",
      "        'doctor:check environment and configuration health'",
      "        'completion:generate shell completion scripts'",
      '    )',
      '    _arguments -C \\',
      "        '-o[Output format]:format:(text json csv markdown)' \\",
      "        '--output[Output format]:format:(text json csv markdown)' \\",
      "        '--json[Shorthand for --output json]' \\",
      "        '--output-file[Write results to file]:file:_files' \\",
      "        '--log-level[Explicit console log level]:level:(debug info warning error critical)' \\",
      "        '--log-file[Enable rotating file logging]::file:_files' \\",
      "        '*-v[Increase verbosity]' \\",
      "        '*--verbose[Increase verbosity]' \\",
      "        '-q[Suppress non-essential stderr output]' \\",
      "        '--quiet[Suppress non-essential stderr output]' \\",
      "        '--debug[Maximum diagnostics]' \\",
      "        '--no-color[Disable colored output]' \\",
      "        '--no-input[Never prompt; disable interactive pager]' \\",
      "        '--config[Path to config file]:file:_files' \\",
      "        '--token[Personal access token]:token:' \\",
      "        '1:command:->cmds' \\",
      "        '*::arg:->args'",
      '    case "$state" in',
      '        cmds)',
      `            _describe -t commands '${bin} commands' commands`,
      '            ;;',
      '        args)',
      '            case "$line[1]" in',
      '                projects)',
      '                    _arguments -C \\',
      "                        '1:subcommand:(list get)' \\",
      "                        '*::arg:->proj_args'",
      '                    if [[ "$state" == "proj_args" ]]; then',
      '                        _arguments \\',
      "                            '--workspace[Filter projects by workspace name]:name:' \\",
      "                            '--limit[Maximum number of projects]:n:' \\",
      "                            '--source[Data source]:source:(http memory)' \\",
      "                            '--copy[Copy results to clipboard]'",
      '                    fi',
      '                    ;;',
      '                config)',
      '                    _arguments -C \\',
      "                        '1:subcommand:(init path get set)' \\",
      "                        '*::arg:->cfg_args'",
      '                    if [[ "$state" == "cfg_args" ]]; then',
      '                        case "$line[1]" in',
      '                            get)',
      '                                _arguments \\',
      "                                    '1:key:(logging.file logging.file_level logging.format logging.level output.color output.format token)'",
      '                                ;;',
      '                            set)',
      '                                _arguments \\',
      "                                    '1:key:(logging.file logging.file_level logging.format logging.level output.color output.format)' \\",
      "                                    '2:value:' \\",
      "                                    '--dry-run[Show what would change; write nothing]' \\",
      "                                    '-y[Skip overwrite confirmation]' \\",
      "                                    '--yes[Skip overwrite confirmation]'",
      '                                ;;',
      '                            init)',
      '                                _arguments \\',
      "                                    '--dry-run[Show what would change; write nothing]' \\",
      "                                    '-y[Accept defaults without prompting]' \\",
      "                                    '--yes[Accept defaults without prompting]'",
      '                                ;;',
      '                        esac',
      '                    fi',
      '                    ;;',
      '                doctor)',
      '                    _arguments \\',
      "                        '--bundle[Collect a redacted diagnostics bundle]'",
      '                    ;;',
      '                completion)',
      '                    _arguments \\',
      "                        '1:shell:(bash zsh fish)'",
      '                    ;;',
      '            esac',
      '            ;;',
      '    esac',
      '}',
      '',
      `if [ "\${funcstack[1]}" = "${fnName}" ]; then`,
      `    ${fnName} "$@"`,
      'else',
      `    compdef ${fnName} ${bin}`,
      'fi',
      '',
    ].join('\n');
  }

  return [
    `# fish completion for ${bin}`,
    `function ${fnName}`,
    '    set -l cmd (commandline -opc)',
    '    set -l pos',
    '    set -l i 2',
    '    set -l total (count $cmd)',
    '    while test $i -le $total',
    '        set -l tok "$cmd[$i]"',
    '        switch $tok',
    '            case -o --output --output-file --log-level --config --token --workspace --limit --source',
    '                set i (math $i + 2)',
    '                continue',
    '            case --log-file',
    '                set -l next_idx (math $i + 1)',
    '                if test $next_idx -le $total',
    '                    set -l nxt "$cmd[$next_idx]"',
    '                    if not string match -qr "^-" -- "$nxt"; and not contains -- "$nxt" projects config doctor completion',
    '                        set i (math $i + 2)',
    '                        continue',
    '                    end',
    '                end',
    '                set i (math $i + 1)',
    '                continue',
    "            case '-*'",
    '                set i (math $i + 1)',
    '                continue',
    "            case '*'",
    '                set -a pos "$tok"',
    '                set i (math $i + 1)',
    '        end',
    '    end',
    '    if test (count $pos) -eq 0',
    '        printf "%s\\n" projects config doctor completion',
    '    else if test "$pos[1]" = "projects"',
    '        if test (count $pos) -eq 1',
    '            printf "%s\\n" list get',
    '        else',
    '            printf "%s\\n" --workspace --limit --source --copy',
    '        end',
    '    else if test "$pos[1]" = "config"',
    '        if test (count $pos) -eq 1',
    '            printf "%s\\n" init path get set',
    '        else if test "$pos[2]" = "get" -a (count $pos) -eq 2',
    '            printf "%s\\n" logging.file logging.file_level logging.format logging.level output.color output.format token',
    '        else if test "$pos[2]" = "set" -a (count $pos) -eq 2',
    '            printf "%s\\n" logging.file logging.file_level logging.format logging.level output.color output.format',
    '        else if contains -- "$pos[2]" init set',
    '            printf "%s\\n" --dry-run -y --yes',
    '        end',
    '    else if test "$pos[1]" = "doctor"',
    '        printf "%s\\n" --bundle',
    '    else if test "$pos[1]" = "completion" -a (count $pos) -eq 1',
    '        printf "%s\\n" bash zsh fish',
    '    end',
    'end',
    '',
    `complete --no-files --command ${bin} --arguments "(${fnName})"`,
    '',
  ].join('\n');
}

/** Register the `completion <shell>` command. */
export function registerCompletionCommand(
  program: Command,
  deps: CliDeps,
  initContext: (commandPath: string) => CliContext
): void {
  program
    .command('completion')
    .description('generate shell completion script (bash, zsh, fish)')
    .addArgument(new Argument('<shell>', 'target shell').choices(COMPLETION_SHELLS))
    .action((shell: CompletionShell) => {
      const ctx = initContext('completion');
      const script = renderCompletionScript(shell);
      if (ctx.outputFile !== undefined) {
        if (deps.fs !== undefined) {
          deps.fs.writeFileSync(ctx.outputFile, script, {});
        } else {
          writeFileSync(ctx.outputFile, script, 'utf8');
        }
        ctx.message(ctx.colors.success(`Results written to ${ctx.outputFile}`));
      } else {
        deps.stdout(script);
      }
    });
}
